'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const atlas=fs.readFileSync(path.join(root,'assets/character-atlas-v3.png'));
assert.equal(atlas.subarray(0,8).toString('hex'),'89504e470d0a1a0a','Invalid PNG');
assert.equal(atlas.readUInt32BE(16),384,'Atlas must be 4 × 96');
assert.equal(atlas.readUInt32BE(20),672,'Atlas must be 6 × 112');
assert.equal(atlas[25],6,'Atlas requires RGBA transparency');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const raster=read('raster.js');
const patient=read('pixel-polish.js');
const guard=read('pursuit-polish.js');
const html=read('index.html');
assert(raster.includes("CHARACTER_ATLAS_PATH='assets/character-atlas-v3.png?v=3'"));
assert(raster.includes("CHARACTER_ATLAS_ROWS={guard:0,patient05:2,dalsu:4}"));
assert(raster.includes("Math.floor(frameTime*5)%2"),'Walking frame toggle missing');
assert(raster.includes("['nurse','guard','dalsu','patient05'].includes(kind)&&drawAtlasSprite"),'Atlas not used before procedural fallback');
assert(patient.includes("drawAtlasSprite('patient05',x,y,face)"));
assert(guard.includes("drawAtlasSprite('guard',x,y,face)"));
for(const file of ['raster.js','pixel-polish.js','pursuit-polish.js'])assert(html.includes(file+'?v=character-atlas-v3'),file+' cache not refreshed');
console.log(JSON.stringify({passed:true,atlasBytes:atlas.length,characters:3,frameCount:24,frameSize:[96,112]},null,2));
