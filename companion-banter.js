function partyBanterAvailable(party){
 if(!Array.isArray(party))return [];
 return PARTY_BANTER.filter(story=>story.people.every(id=>party.includes(id)));
}
(()=>{
 for(const story of PARTY_BANTER){
  const root='partyBanter_'+story.id;
  if(SCRIPTS[root])throw Error('Duplicate banter scene '+root);
  SCRIPTS[root]=[Q(story.flag,root+'After',root+'Before')];
  for(const branch of ['Before','After']){
   const lines=branch==='Before'?story.early:story.late;
   // Their own topic is optional and never forces progress or rewards.
   SCRIPTS[root+branch]=lines.map(([who,text])=>T(text,who));
  }
 }
})();
function openPartyBanterMenu(){
 const choices=partyBanterAvailable(s.party);
 if(!choices.length){openCompanionTalkMenu();return}
 const panel=modal('동료들 사이의 대화');
 paragraph(panel,'함께 있는 사람들이 서로 다른 경험을 비교한다. 각자의 증거를 확보하면 같은 주제라도 다른 이야기를 들을 수 있다.','small');
 const topics=row(panel);
 for(const entry of choices){
  const names={kim:'차준영',jubin:'김주호',changwon:'이철민',nasol:'오은지',patient05:'서정윤'};
  const people=entry.people.map(x=>names[x]).join(' · ');
  button(topics,entry.title+'\n'+people,()=>{
   closeModal();
   run('partyBanter_'+entry.id);
  },'banterTopic');
 }
 const nav=row(panel);
 button(nav,'동료 선택으로',openCompanionTalkMenu);
 button(nav,'게임으로',closeModal,'primary');
}
